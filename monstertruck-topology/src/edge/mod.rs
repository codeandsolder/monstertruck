use crate::{
    Arc, BoundedCurve, Concat, CurveParameter, Cut, Debug, DebugDisplay, Edge, EdgeDisplayFormat,
    EdgeId, Formatter, Hash, Hasher, Id, Invertible, KERNEL_EPSILON, Mutex, MutexFmt,
    ParameterTransform, Result, SEARCH_PARAMETER_TRIALS, SearchParameter, StableId, Tolerance,
    Vertex, errors::Error,
};
use thiserror::Error;

impl<P, C> Edge<P, C> {
    /// Generates the edge from `front` to `back`, validating that the vertices differ.
    ///
    /// # Errors
    /// Returns [`Error::SameVertex`] if `front == back`.
    #[inline]
    pub fn new(front: &Vertex<P>, back: &Vertex<P>, curve: C) -> Result<Self> {
        if front == back {
            Err(Error::SameVertex)
        } else {
            Ok(Self::new_unchecked(front, back, curve))
        }
    }

    /// Generates the edge from `front` to `back` without checking that the vertices differ.
    ///
    /// Callers must establish `front != back` before using this constructor.
    #[inline]
    pub fn new_unchecked(front: &Vertex<P>, back: &Vertex<P>, curve: C) -> Self {
        Self {
            vertices: (front.clone(), back.clone()),
            orientation: true,
            curve: Arc::new(Mutex::new(curve)),
            stable_id: StableId::UNASSIGNED,
        }
    }

    /// Returns the stable persistent identifier of this edge.
    #[inline]
    #[must_use]
    pub const fn stable_id(&self) -> StableId { self.stable_id }

    /// Sets the stable persistent identifier of this edge.
    #[inline]
    pub const fn set_stable_id(&mut self, id: StableId) { self.stable_id = id; }
    /// Returns the orientation of the curve.
    /// # Examples
    /// ```
    /// use monstertruck_topology::*;
    /// let v = Vertex::from_points(&[(), ()]);
    /// let edge0 = Edge::new_unchecked(&v[0], &v[1], ());
    /// let edge1 = edge0.inverse();
    /// assert!(edge0.orientation());
    /// assert!(!edge1.orientation());
    /// ```
    #[inline]
    #[must_use]
    pub const fn orientation(&self) -> bool { self.orientation }

    /// Inverts the direction of edge.
    /// ```
    /// use monstertruck_topology::*;
    /// let v = Vertex::from_points(&[(), ()]);
    /// let edge = Edge::new_unchecked(&v[0], &v[1], ());
    /// let mut inv_edge = edge.clone();
    /// inv_edge.invert();
    ///
    /// // Two edges are the same edge.
    /// edge.is_same(&inv_edge);
    ///
    /// // the front and back are exchanged.
    /// assert_eq!(edge.front(), inv_edge.back());
    /// assert_eq!(edge.back(), inv_edge.front());
    /// ```
    #[inline]
    pub const fn invert(&mut self) -> &mut Self {
        self.orientation = !self.orientation;
        self
    }

    /// Creates the inverse oriented edge.
    /// ```
    /// use monstertruck_topology::*;
    /// let v = Vertex::from_points(&[(), ()]);
    /// let edge = Edge::new_unchecked(&v[0], &v[1], ());
    /// let inv_edge = edge.inverse();
    ///
    /// // Two edges are the same edge.
    /// assert!(edge.is_same(&inv_edge));
    ///
    /// // Two edges has the same id.
    /// assert_eq!(edge.id(), inv_edge.id());
    ///
    /// // the front and back are exchanged.
    /// assert_eq!(edge.front(), inv_edge.back());
    /// assert_eq!(edge.back(), inv_edge.front());
    /// ```
    #[inline]
    #[must_use]
    pub fn inverse(&self) -> Self {
        Self {
            vertices: self.vertices.clone(),
            orientation: !self.orientation,
            curve: Arc::clone(&self.curve),
            stable_id: self.stable_id,
        }
    }

    /// Returns the front vertex
    /// ```
    /// use monstertruck_topology::*;
    /// let v = Vertex::from_points(&[(), ()]);
    /// let edge = Edge::new_unchecked(&v[0], &v[1], ());
    /// assert_eq!(edge.front(), &v[0]);
    /// ```
    #[inline]
    #[must_use]
    pub const fn front(&self) -> &Vertex<P> {
        if self.orientation {
            &self.vertices.0
        } else {
            &self.vertices.1
        }
    }

    /// Returns the back vertex
    /// ```
    /// use monstertruck_topology::*;
    /// let v = Vertex::from_points(&[(), ()]);
    /// let edge = Edge::new_unchecked(&v[0], &v[1], ());
    /// assert_eq!(edge.back(), &v[1]);
    /// ```
    #[inline]
    #[must_use]
    pub const fn back(&self) -> &Vertex<P> {
        if self.orientation {
            &self.vertices.1
        } else {
            &self.vertices.0
        }
    }

    /// Returns the vertices at both ends.
    /// ```
    /// use monstertruck_topology::*;
    /// let v = Vertex::from_points(&[(), ()]);
    /// let edge = Edge::new_unchecked(&v[0], &v[1], ());
    /// assert_eq!(edge.ends(), (&v[0], &v[1]));
    /// ```
    #[inline]
    #[must_use]
    pub const fn ends(&self) -> (&Vertex<P>, &Vertex<P>) {
        if self.orientation {
            (&self.vertices.0, &self.vertices.1)
        } else {
            (&self.vertices.1, &self.vertices.0)
        }
    }

    /// Returns the front vertex which is generated by constructor
    /// ```
    /// use monstertruck_topology::*;
    /// let v = Vertex::from_points(&[(), ()]);
    /// let edge = Edge::new_unchecked(&v[0], &v[1], ()).inverse();
    /// assert_eq!(edge.front(), &v[1]);
    /// assert_eq!(edge.absolute_front(), &v[0]);
    /// ```
    #[inline]
    #[must_use]
    pub const fn absolute_front(&self) -> &Vertex<P> { &self.vertices.0 }
    /// Returns the back vertex which is generated by constructor
    /// ```
    /// use monstertruck_topology::*;
    /// let v = Vertex::from_points(&[(), ()]);
    /// let edge = Edge::new_unchecked(&v[0], &v[1], ()).inverse();
    /// assert_eq!(edge.back(), &v[0]);
    /// assert_eq!(edge.absolute_back(), &v[1]);
    /// ```
    #[inline]
    #[must_use]
    pub const fn absolute_back(&self) -> &Vertex<P> { &self.vertices.1 }

    /// Returns the vertices at both absolute ends.
    /// ```
    /// use monstertruck_topology::*;
    /// let v = Vertex::from_points(&[(), ()]);
    /// let mut edge = Edge::new_unchecked(&v[0], &v[1], ());
    /// edge.invert();
    /// assert_eq!(edge.ends(), (&v[1], &v[0]));
    /// assert_eq!(edge.absolute_ends(), (&v[0], &v[1]));
    /// ```
    #[inline]
    #[must_use]
    pub const fn absolute_ends(&self) -> (&Vertex<P>, &Vertex<P>) {
        (&self.vertices.0, &self.vertices.1)
    }

    /// Returns a clone of the edge without inversion.
    /// # Examples
    /// ```
    /// use monstertruck_topology::{Vertex, Edge};
    /// let v = Vertex::from_points(&[(), ()]);
    /// let edge0 = Edge::new_unchecked(&v[0], &v[1], ());
    /// let edge1 = edge0.inverse();
    /// let edge2 = edge1.absolute_clone();
    /// assert_eq!(edge0, edge2);
    /// assert_ne!(edge1, edge2);
    /// assert!(edge1.is_same(&edge2));
    /// ```
    #[inline]
    #[must_use]
    pub fn absolute_clone(&self) -> Self {
        Self {
            vertices: self.vertices.clone(),
            curve: Arc::clone(&self.curve),
            orientation: true,
            stable_id: self.stable_id,
        }
    }

    /// Returns whether two edges are the same. Returns `true` even if the orientaions are different.
    /// ```
    /// use monstertruck_topology::{Vertex, Edge};
    /// let v = Vertex::from_points(&[(), ()]);
    /// let edge0 = Edge::new_unchecked(&v[0], &v[1], ());
    /// let edge1 = Edge::new_unchecked(&v[0], &v[1], ());
    /// let edge2 = edge0.clone();
    /// let edge3 = edge0.inverse();
    /// assert!(!edge0.is_same(&edge1)); // edges whose ids are different are not the same.
    /// assert!(edge0.is_same(&edge2)); // The cloned edge is the same edge.
    /// assert!(edge0.is_same(&edge3)); // The inversed edge is the "same" edge
    /// ```
    #[inline]
    #[must_use]
    pub fn is_same(&self, other: &Self) -> bool { self.id() == other.id() }

    /// Returns the clone of the curve.
    /// # Remarks
    /// This method returns absolute curve i.e. does not consider the orientation of curve.
    /// If you want to get a curve compatible with edge's orientation, use `Edge::oriented_curve`.
    /// ```
    /// use monstertruck_topology::*;
    /// let v = Vertex::from_points(&[0, 1]);
    /// let mut edge = Edge::new_unchecked(&v[0], &v[1], (0, 1));
    /// edge.invert();
    ///
    /// // absolute curve
    /// assert_eq!(edge.curve(), (0, 1));
    /// // oriented curve
    /// assert_eq!(edge.oriented_curve(), (1, 0));
    /// ```
    #[inline]
    #[must_use]
    pub fn curve(&self) -> C
    where C: Clone {
        self.curve.lock().clone()
    }

    /// Calls `f` with a borrowed reference to the edge curve.
    #[inline]
    pub fn with_curve<R>(&self, f: impl FnOnce(&C) -> R) -> R { f(&self.curve.lock()) }

    /// Set the curve.
    /// # Examples
    /// ```
    /// use monstertruck_topology::*;
    /// let v = Vertex::from_points(&[(), ()]);
    /// let edge0 = Edge::new_unchecked(&v[0], &v[1], 0);
    /// let edge1 = edge0.clone();
    ///
    /// // Two edges have the same content.
    /// assert_eq!(edge0.curve(), 0);
    /// assert_eq!(edge1.curve(), 0);
    ///
    /// // set the content
    /// edge0.set_curve(1);
    ///
    /// // The contents of two edges are synchronized.
    /// assert_eq!(edge0.curve(), 1);
    /// assert_eq!(edge1.curve(), 1);
    /// ```
    #[inline]
    pub fn set_curve(&self, curve: C) { *self.curve.lock() = curve; }

    /// Returns the id that does not depend on the direction of the edge.
    /// # Examples
    /// ```
    /// use monstertruck_topology::*;
    /// let v = Vertex::from_points(&[(), ()]);
    /// let edge0 = Edge::new_unchecked(&v[0], &v[1], ());
    /// let edge1 = edge0.inverse();
    /// assert_ne!(edge0, edge1);
    /// assert_eq!(edge0.id(), edge1.id());
    /// ```
    #[inline]
    #[must_use]
    pub fn id(&self) -> EdgeId<C> { Id::new(Arc::as_ptr(&self.curve)) }

    /// Returns how many same edges.
    ///
    /// # Examples
    /// ```
    /// use monstertruck_topology::*;
    ///
    /// // Create one edge
    /// let v = Vertex::from_points(&[(), ()]);
    /// let e0 = Edge::new_unchecked(&v[0], &v[1], ());
    /// assert_eq!(e0.count(), 1);
    ///
    /// // Create another edge, independent from e0
    /// let e1 = Edge::new_unchecked(&v[0], &v[1], ());
    /// assert_eq!(e0.count(), 1);
    ///
    /// // Clone e0, count will be 2
    /// let e2 = e0.clone();
    /// assert_eq!(e0.count(), 2);
    /// assert_eq!(e2.count(), 2);
    ///
    /// // drop e2, count will be 1
    /// drop(e2);
    /// assert_eq!(e0.count(), 1);
    /// ```
    #[inline]
    #[must_use]
    pub fn count(&self) -> usize { Arc::strong_count(&self.curve) }

    /// Returns the cloned curve in edge.
    /// If edge is inverted, then the returned curve is also inverted.
    #[inline]
    #[must_use]
    pub fn oriented_curve(&self) -> C
    where C: Clone + Invertible {
        if self.orientation {
            self.curve.lock().clone()
        } else {
            self.curve.lock().inverse()
        }
    }

    /// Returns a new edge whose curve is mapped by `curve_mapping` and
    /// whose end points are mapped by `point_mapping`.
    /// # Remarks
    /// Accessing geometry elements directly in the closure will result in a deadlock.
    /// So, this method does not appear to the document.
    #[doc(hidden)]
    #[inline]
    pub fn try_mapped<Q, D>(
        &self,
        mut point_mapping: impl FnMut(&P) -> Option<Q>,
        mut curve_mapping: impl FnMut(&C) -> Option<D>,
    ) -> Option<Edge<Q, D>> {
        let v0 = self.absolute_front().try_mapped(&mut point_mapping)?;
        let v1 = self.absolute_back().try_mapped(&mut point_mapping)?;
        let curve = curve_mapping(&*self.curve.lock())?;
        // `.ok()?` rather than a panic (spec 012 U4): this signature already
        // promises `None`. Measured dead as well as typed -- `Vertex::try_mapped`
        // builds a FRESH `Arc` per call and `Vertex` identity is
        // `Arc::as_ptr`, so `v0 == v1` is unreachable here whatever the
        // receiver looks like. Recorded rather than asserted (C5).
        let mut edge = Edge::new(&v0, &v1, curve).ok()?;
        if !self.orientation() {
            edge.invert();
        }
        Some(edge)
    }

    /// Returns a new edge whose curve is mapped by `curve_mapping` and
    /// whose end points are mapped by `point_mapping`.
    /// # Examples
    /// ```
    /// use monstertruck_topology::*;
    /// let v0 = Vertex::new(0);
    /// let v1 = Vertex::new(1);
    /// let edge0 = Edge::new_unchecked(&v0, &v1, 2);
    /// let edge1 = edge0.mapped(
    ///     &move |i: &usize| *i as f64 + 0.5,
    ///     &move |j: &usize| *j as f64 + 0.5,
    /// );
    ///
    /// assert_eq!(edge1.front().point(), 0.5);
    /// assert_eq!(edge1.back().point(), 1.5);
    /// assert_eq!(edge1.curve(), 2.5);
    /// ```
    /// # Remarks
    /// Accessing geometry elements directly in the closure will result in a deadlock.
    /// So, this method does not appear to the document.
    #[doc(hidden)]
    #[inline]
    pub fn mapped<Q, D>(
        &self,
        mut point_mapping: impl FnMut(&P) -> Q,
        mut curve_mapping: impl FnMut(&C) -> D,
    ) -> Edge<Q, D> {
        let v0 = self.absolute_front().mapped(&mut point_mapping);
        let v1 = self.absolute_back().mapped(&mut point_mapping);
        let curve = curve_mapping(&*self.curve.lock());
        // Infallible signature, no channel -- and unlike the general case this
        // one is PROVABLY total, so nothing is being swallowed: `Vertex::mapped`
        // is `Vertex::new_with_id`, a fresh `Arc` per call, and `Vertex`
        // equality is `Arc::as_ptr` equality, so `v0 == v1` cannot hold. Stated
        // as `new_unchecked` rather than hiding the invariant behind a build-profile switch
        // switch (spec 012 U4).
        let mut edge = Edge::new_unchecked(&v0, &v1, curve);
        if edge.orientation() != self.orientation() {
            edge.invert();
        }
        edge
    }

    /// Returns the consistence of the geometry of end vertices
    /// and the geometry of edge.
    #[inline]
    #[must_use]
    pub fn is_geometric_consistent(&self) -> bool
    where
        P: Tolerance,
        C: BoundedCurve<Point = P>, {
        let (geom_front, geom_back) = {
            let curve = self.curve.lock();
            (curve.front(), curve.back())
        };
        let top_front = self.absolute_front().point.lock();
        let top_back = self.absolute_back().point.lock();
        geom_front.near(&*top_front) && geom_back.near(&*top_back)
    }

    #[inline]
    fn pre_cut(&self, vertex: &Vertex<P>, mut curve0: C, t: f64) -> (Self, Self)
    where C: Cut<Point = P> {
        let curve1 = curve0.cut(t);
        let edge0 = Self {
            vertices: (self.absolute_front().clone(), vertex.clone()),
            orientation: self.orientation,
            curve: Arc::new(Mutex::new(curve0)),
            stable_id: StableId::UNASSIGNED,
        };
        let edge1 = Self {
            vertices: (vertex.clone(), self.absolute_back().clone()),
            orientation: self.orientation,
            curve: Arc::new(Mutex::new(curve1)),
            stable_id: StableId::UNASSIGNED,
        };
        if self.orientation {
            (edge0, edge1)
        } else {
            (edge1, edge0)
        }
    }

    /// Cuts the edge at `vertex`.
    /// # Failures
    /// Returns `None` if:
    /// - cannot find the parameter `t` such that `edge.curve().evaluate(t) == vertex.point()`, or
    /// - the found parameter is not in the parameter range without end points.
    #[must_use]
    pub fn cut(&self, vertex: &Vertex<P>) -> Option<(Self, Self)>
    where
        P: Clone,
        C: Cut<Point = P> + SearchParameter<CurveParameter, Point = P>, {
        let curve0 = self.curve();
        let t = curve0.search_parameter(vertex.point(), None, SEARCH_PARAMETER_TRIALS)?;
        let (t0, t1) = curve0.range_tuple();
        if t < t0 + KERNEL_EPSILON || t1 - KERNEL_EPSILON < t {
            return None;
        }
        Some(self.pre_cut(vertex, curve0, t))
    }

    /// Cuts the edge at `vertex` with parameter `t`.
    /// # Failure
    /// Returns `None` if `!edge.curve().evaluate(t).near(&vertex.point())`.
    #[must_use]
    pub fn cut_with_parameter(&self, vertex: &Vertex<P>, t: f64) -> Option<(Self, Self)>
    where
        P: Clone + Tolerance,
        C: Cut<Point = P>, {
        let curve0 = self.curve();
        if !curve0.evaluate(t).near(&vertex.point()) {
            return None;
        }
        let (t0, t1) = curve0.range_tuple();
        if t < t0 + KERNEL_EPSILON || t1 - KERNEL_EPSILON < t {
            return None;
        }
        Some(self.pre_cut(vertex, curve0, t))
    }

    /// Concats two edges.
    ///
    /// # Errors
    /// Returns an error when the edges are disconnected, would close onto the
    /// same vertex, or their oriented curves cannot be concatenated.
    pub fn concat(&self, rhs: &Self) -> std::result::Result<Self, ConcatError<P>>
    where
        P: Debug,
        C: Concat<C, Point = P, Output = C> + Invertible + ParameterTransform, {
        if self.back() != rhs.front() {
            return Err(ConcatError::DisconnectedVertex(
                self.back().clone(),
                rhs.front().clone(),
            ));
        }
        if self.front() == rhs.back() {
            return Err(ConcatError::SameVertex(self.front().clone()));
        }
        let curve0 = self.oriented_curve();
        let mut curve1 = rhs.oriented_curve();
        let t0 = curve0.range_tuple().1;
        let t1 = curve1.range_tuple().0;
        curve1.parameter_transform(1.0, t0 - t1);
        let curve = curve0.try_concat(&curve1)?;
        // The `front == back` violation checked construction rejects is the same one
        // `ConcatError::SameVertex` names, and it was already rejected above --
        // so this maps a redundant check onto the error this function already
        // has, rather than unwrapping it (spec 012 U4: a panic that moves looks
        // exactly like a panic that was fixed).
        Self::new(self.front(), rhs.back(), curve)
            .map_err(|_| ConcatError::SameVertex(self.front().clone()))
    }

    /// Create display struct for debugging the edge.
    ///
    /// # Examples
    /// ```
    /// use monstertruck_topology::*;
    /// use EdgeDisplayFormat as Edf;
    ///
    /// let vertex_format = VertexDisplayFormat::AsPoint;
    /// let edge = Edge::new_unchecked(&Vertex::new(0), &Vertex::new(1), 2);
    /// let id = edge.id();
    ///
    /// assert_eq!(
    ///     format!("{:?}", edge.display(Edf::Full { vertex_format })),
    ///     format!("Edge {{ id: {id:?}, vertices: (0, 1), entity: 2 }}"),
    /// );
    /// assert_eq!(
    ///     format!("{:?}", edge.display(Edf::VerticesTupleAndID { vertex_format })),
    ///     format!("Edge {{ id: {id:?}, vertices: (0, 1) }}"),
    /// );
    /// assert_eq!(
    ///     &format!("{:?}", edge.display(Edf::VerticesTupleAndCurve { vertex_format })),
    ///     "Edge { vertices: (0, 1), entity: 2 }",
    /// );
    /// assert_eq!(
    ///     &format!("{:?}", edge.display(Edf::VerticesTupleStruct { vertex_format })),
    ///     "Edge(0, 1)",
    /// );
    /// assert_eq!(
    ///     &format!("{:?}", edge.display(Edf::VerticesTuple { vertex_format })),
    ///     "(0, 1)",
    /// );
    /// assert_eq!(
    ///     &format!("{:?}", edge.display(Edf::AsCurve)),
    ///     "2",
    /// );
    /// ```
    #[inline]
    #[must_use]
    pub const fn display(
        &self,
        format: EdgeDisplayFormat,
    ) -> DebugDisplay<'_, Self, EdgeDisplayFormat> {
        DebugDisplay {
            entity: self,
            format,
        }
    }
}

/// Error for concat
#[derive(Clone, Debug, Error)]
pub enum ConcatError<P: Debug> {
    /// Failed to concat edges since the end point of the first curve is different from the start point of the second curve.
    #[error(
        "The end point {0:?} of the first curve is different from the start point {1:?} of the second curve."
    )]
    DisconnectedVertex(Vertex<P>, Vertex<P>),
    #[error("The end vertices are the same vertex {0:?}.")]
    SameVertex(Vertex<P>),
    /// From geometric error.
    #[error("{0}")]
    FromGeometry(monstertruck_traits::ConcatError<P>),
}

impl<P: Debug> From<monstertruck_traits::ConcatError<P>> for ConcatError<P> {
    fn from(err: monstertruck_traits::ConcatError<P>) -> Self { Self::FromGeometry(err) }
}

impl<P, C> Clone for Edge<P, C> {
    #[inline]
    fn clone(&self) -> Self {
        Self {
            vertices: self.vertices.clone(),
            orientation: self.orientation,
            curve: Arc::clone(&self.curve),
            stable_id: self.stable_id,
        }
    }
}

impl<P, C> PartialEq for Edge<P, C> {
    #[inline]
    fn eq(&self, other: &Self) -> bool {
        std::ptr::eq(Arc::as_ptr(&self.curve), Arc::as_ptr(&other.curve))
            && self.orientation == other.orientation
    }
}

impl<P, C> Eq for Edge<P, C> {}

impl<P, C> Hash for Edge<P, C> {
    #[inline]
    fn hash<H: Hasher>(&self, state: &mut H) {
        std::ptr::hash(Arc::as_ptr(&self.curve), state);
        self.orientation.hash(state);
    }
}

impl<P: Debug, C: Debug> Debug for DebugDisplay<'_, Edge<P, C>, EdgeDisplayFormat> {
    fn fmt(&self, f: &mut Formatter<'_>) -> std::fmt::Result {
        match self.format {
            EdgeDisplayFormat::Full { vertex_format } => f
                .debug_struct("Edge")
                .field("id", &Arc::as_ptr(&self.entity.curve))
                .field(
                    "vertices",
                    &(
                        self.entity.front().display(vertex_format),
                        self.entity.back().display(vertex_format),
                    ),
                )
                .field("entity", &MutexFmt(&self.entity.curve))
                .finish(),
            EdgeDisplayFormat::VerticesTupleAndID { vertex_format } => f
                .debug_struct("Edge")
                .field("id", &self.entity.id())
                .field(
                    "vertices",
                    &(
                        self.entity.front().display(vertex_format),
                        self.entity.back().display(vertex_format),
                    ),
                )
                .finish(),
            EdgeDisplayFormat::VerticesTupleAndCurve { vertex_format } => f
                .debug_struct("Edge")
                .field(
                    "vertices",
                    &(
                        self.entity.front().display(vertex_format),
                        self.entity.back().display(vertex_format),
                    ),
                )
                .field("entity", &MutexFmt(&self.entity.curve))
                .finish(),
            EdgeDisplayFormat::VerticesTupleStruct { vertex_format } => f
                .debug_tuple("Edge")
                .field(&self.entity.front().display(vertex_format))
                .field(&self.entity.back().display(vertex_format))
                .finish(),
            EdgeDisplayFormat::VerticesTuple { vertex_format } => f.write_fmt(format_args!(
                "({:?}, {:?})",
                self.entity.front().display(vertex_format),
                self.entity.back().display(vertex_format),
            )),
            EdgeDisplayFormat::AsCurve => {
                f.write_fmt(format_args!("{:?}", MutexFmt(&self.entity.curve)))
            }
        }
    }
}
